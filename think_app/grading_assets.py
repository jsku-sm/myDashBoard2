"""Validated, explicitly labelled model inputs for teacher-requested grading."""
import base64
from collections.abc import Mapping
import json
import math
from pathlib import Path

from .storage import AppError


def _sequence(value, limit, label):
    value = [] if value is None else value
    if not isinstance(value, (list, tuple)) or len(value) > limit:
        raise AppError(f"{label} 첨부 정보를 확인하세요.")
    return value


def _text(row, field):
    value = row.get(field, "")
    if not isinstance(value, str):
        raise AppError("자동 채점에 사용할 문제와 답안의 글 형식을 확인하세요.")
    return value


def _graph(value):
    if value is None:
        return {}
    if not isinstance(value, Mapping) or not isinstance(value.get("expressions"), list):
        raise AppError("자동 채점에 사용할 그래프 수식과 표를 확인하세요.")
    expressions = []
    for expression in value["expressions"]:
        if not isinstance(expression, Mapping):
            raise AppError("자동 채점에 사용할 그래프 수식을 확인하세요.")
        projected = {"type": "table" if expression.get("type") == "table" else "expression",
                     "latex": _text(expression, "latex")}
        if projected["type"] == "table":
            columns = expression.get("columns", [])
            if not isinstance(columns, list):
                raise AppError("자동 채점에 사용할 그래프 표를 확인하세요.")
            projected["columns"] = []
            for column in columns:
                if not isinstance(column, Mapping) or not isinstance(column.get("values", []), list):
                    raise AppError("자동 채점에 사용할 그래프 표를 확인하세요.")
                values = column.get("values", [])
                if any(not isinstance(cell, (str, int, float)) or isinstance(cell, bool) or
                       isinstance(cell, float) and not math.isfinite(cell) for cell in values):
                    raise AppError("자동 채점에 사용할 그래프 표의 값을 확인하세요.")
                projected["columns"].append({"latex": _text(column, "latex"), "values": list(values)})
        expressions.append(projected)
    state = value.get("state")
    graph = state.get("graph") if isinstance(state, Mapping) else None
    viewport = graph.get("viewport", {}) if isinstance(graph, Mapping) else {}
    projected = {"expressions": expressions}
    if isinstance(viewport, Mapping):
        projected["viewport"] = {key: number for key in ("xmin", "xmax", "ymin", "ymax")
                                 if isinstance(number := viewport.get(key), (int, float)) and
                                 not isinstance(number, bool) and math.isfinite(number)}
    try:
        serialized = json.dumps(projected, ensure_ascii=False, allow_nan=False)
    except (ValueError, TypeError):
        raise AppError("자동 채점에 사용할 그래프 형식을 확인하세요.") from None
    if len(expressions) > 100 or len(serialized.encode()) > 500_000:
        raise AppError("자동 채점에 사용할 그래프가 너무 큽니다.")
    return projected


def _image(raw):
    # Imported at call time to avoid the question-files/media -> ai dependency.
    from .ai import normalized_image
    if not isinstance(raw, bytes) or not raw:
        raise AppError("자동 채점에 사용할 이미지 내용을 확인하세요.")
    raw = normalized_image(raw)
    return {"type": "input_image", "image_url": "data:image/jpeg;base64," + base64.b64encode(raw).decode(),
            "detail": "high"}, len(raw)


def grading_content(task, attempt, images, documents=None, question_files=None, expected_images=None):
    """Accept student image bytes/PDF tuples and teacher (metadata, bytes) files.

    Identity, file references, names, source URLs, previous feedback and grades
    are not projected into model input. PDF filenames are generated by role.
    """
    from .model_answers import _question_file_content
    from .uploads import validated_pdf

    if not isinstance(task, Mapping) or not isinstance(attempt, Mapping):
        raise AppError("자동 채점에 사용할 저장된 문제와 학생 답안을 확인하세요.")
    images = _sequence(images, 4, "학생 이미지")
    documents = _sequence(documents, 3, "학생 PDF")
    question_files = _sequence(question_files, 5, "교사 문제")
    expected_images = _sequence(expected_images, 3, "교사 모범답안 이미지")
    criteria = task.get("criteria")
    if (not isinstance(criteria, list) or not criteria or not all(isinstance(item, str) and item.strip() for item in criteria) or
            len(criteria) > 100):
        raise AppError("자동 채점에 사용할 평가 기준을 확인하세요.")
    for field, actual in (("question_files", question_files), ("expected_images", expected_images)):
        saved = task.get(field, [])
        if not isinstance(saved, (list, tuple)) or len(saved) != len(actual):
            raise AppError("저장된 문제·모범답안 첨부를 모두 확인한 뒤 자동 채점하세요.")
    expected = _text(task, "expected")
    if not expected.strip() and not expected_images:
        raise AppError("자동 채점에 사용할 모범답안을 먼저 저장하세요.")
    content = [{"type": "input_text", "text": json.dumps({"교사채점자료": {
        "문제": _text(task, "prompt"), "모범답안": expected, "평가기준": list(criteria), "만점": 100}}, ensure_ascii=False)}]
    total_bytes = 0
    for index, item in enumerate(question_files, 1):
        if not isinstance(item, (list, tuple)) or len(item) != 2 or not isinstance(item[0], Mapping):
            raise AppError("자동 채점에 사용할 교사 문제 첨부를 확인하세요.")
        metadata, raw = item
        filename = metadata.get("filename")
        if not isinstance(filename, str) or not isinstance(raw, bytes):
            raise AppError("자동 채점에 사용할 교사 문제 파일을 확인하세요.")
        suffix = Path(filename).suffix.lower()
        safe_name = f"teacher-question-{index}{suffix}"
        parts = _question_file_content(safe_name, raw)
        mime = metadata.get("mime", "")
        expected_type = ("input_image" if isinstance(mime, str) and mime.startswith("image/") else
                         "input_file" if mime == "application/pdf" else "input_text")
        if mime and (not isinstance(mime, str) or parts[-1]["type"] != expected_type):
            raise AppError("교사 문제 파일의 형식과 저장 정보를 확인하세요.")
        content.append({"type": "input_text", "text": f"교사 문제 첨부 {index} · 학생 답안이 아닙니다."})
        content.extend(parts[1:])
        total_bytes += len(raw)
    for index, raw in enumerate(expected_images, 1):
        content.append({"type": "input_text", "text": f"교사 모범답안 이미지 {index} · 비교 기준이며 학생 답안이 아닙니다."})
        image, size = _image(raw)
        content.append(image)
        total_bytes += size

    transcript = _text(attempt, "transcript")
    quiz_answer = attempt.get("quiz_answer")
    if quiz_answer is not None and not isinstance(quiz_answer, str):
        raise AppError("자동 채점에 사용할 학생의 퀴즈 답을 확인하세요.")
    response = {"글로쓴설명": _text(attempt, "text"), "학생이확인한음성전사": transcript,
                "음성전사없음": bool(attempt.get("audio") and not transcript.strip()),
                "수정하며생각한점": _text(attempt, "reflection"),
                "활동모드": attempt.get("mode") if attempt.get("mode") in ("writing", "graph", "quiz") else "writing",
                "퀴즈답": quiz_answer, "그래프수식과표": _graph(attempt.get("graph"))}
    content.append({"type": "input_text", "text": json.dumps({"학생답안": response}, ensure_ascii=False)})
    for index, raw in enumerate(images, 1):
        content.append({"type": "input_text", "text": f"학생 답안 이미지 {index} · 학생이 실제 제출한 풀이입니다."})
        image, size = _image(raw)
        content.append(image)
        total_bytes += size
    for index, item in enumerate(documents, 1):
        if (not isinstance(item, (list, tuple)) or len(item) != 2 or not isinstance(item[0], str) or
                not item[0].lower().endswith(".pdf")):
            raise AppError("자동 채점에 사용할 학생 PDF 첨부를 확인하세요.")
        raw = validated_pdf(item[1])
        content.append({"type": "input_text", "text": f"학생 답안 PDF {index} · 모든 쪽의 실제 풀이를 확인하세요."})
        content.append({"type": "input_file", "filename": f"student-answer-{index}.pdf",
                        "file_data": "data:application/pdf;base64," + base64.b64encode(raw).decode()})
        total_bytes += len(raw)
    if total_bytes > 50_000_000:
        raise AppError("자동 채점 첨부의 합계는 50MB 이하로 줄여주세요.")
    if sum(len(item.get("text", "")) for item in content if item["type"] == "input_text") > 600_000:
        raise AppError("자동 채점에 사용할 문제와 답안 글이 너무 깁니다.")
    return content
