import assert from 'node:assert/strict';
const listeners={},events=[],memory=new Map();
const nodes={lab:{innerHTML:'',addEventListener:(t,f)=>listeners['root:'+t]=f,getBoundingClientRect:()=>({height:1000})},'lab-save':{textContent:'',classList:{toggle(){}}},'lab-retry':{toggleAttribute(){}}};
globalThis.document={getElementById:id=>nodes[id]||null,addEventListener:(t,f)=>listeners['document:'+t]=f};
globalThis.window={parent:{postMessage:m=>events.push(m)},addEventListener:(t,f)=>listeners[t]=f};
globalThis.ResizeObserver=class{observe(){}};
globalThis.sessionStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
await import('../src/main.js');
let args={data:{userId:'test-student',name:'검사 학생',preview:false,revision:0,games:{}},view:'hub'};
const render=patch=>{args={...args,...patch};listeners.message({source:window.parent,data:{type:'streamlit:render',args}});};
const click=(match,dataset={})=>listeners['root:click']({target:{closest:s=>s===match?{dataset}:null}});
render({});assert.equal((nodes.lab.innerHTML.match(/class="lab-card tone-/g)||[]).length,12);
assert.match(nodes.lab.innerHTML,/data-open="avatar"/);assert.match(nodes.lab.innerHTML,/data-open="quiz"/);
click('[data-open]',{open:'avatar'});assert.equal(events.at(-1).value.target,'avatar');
let navigationCount=events.filter(e=>e.value?.action==='navigate').length;
render({view:'header',title:'아바타 퀘스트'});
assert.equal(events.filter(e=>e.value?.action==='navigate').length,navigationCount,'server navigation render must not emit another navigation');
render({view:'arena',gameId:'bubble'});assert.equal(globalThis.mounts,1);
const e={game:'bubble',type:'start',runId:'run-12345678',elapsed:0,stage:1,stageCount:3,mode:'relaxed',score:0};
globalThis.testArcade.onEvent(e);
click('[data-home]');
const batch=events.at(-1).value;assert.equal(batch.action,'record');assert.equal(batch.events.length,1);
render({failed:batch.id,error:'conflict',data:{...args.data,revision:1}});
assert.equal(globalThis.mounts,1,'save acknowledgements must not remount the live game');
click('[data-retry]');const retry=events.at(-1).value;
assert.equal(retry.action,'record');assert.equal(retry.revision,1);assert.deepEqual(retry.events,batch.events);
render({ack:retry.id,failed:null,error:'',data:{...args.data,revision:2}});
assert.equal(events.at(-1).value.target,'hub');assert.equal(globalThis.mounts,1);
navigationCount=events.filter(e=>e.value?.action==='navigate').length;
render({view:'hub',gameId:null});
assert.equal(events.filter(e=>e.value?.action==='navigate').length,navigationCount);
const stored=JSON.parse([...memory.values()][0]);assert.equal(stored.pending.length,0);
console.log('PASS: 12 games, avatar/quiz routes, save before navigation, conflict retry and stable live game');
process.exit(0);
